#!/usr/bin/env php
<?php

declare(strict_types=1);

/*
 * Regenerates src/UI/simple-icons.php from the SimpleIcons project (CC0-1.0).
 * Usage: php scripts/update-icons.php
 *
 * Microsoft and LinkedIn were removed from recent SimpleIcons releases at the
 * brands' request, so they are pinned to the last major version that had them.
 */

const ICONS = [
    // slug => [title, simple-icons major version]
    'google' => ['Google', 13],
    'github' => ['GitHub', 13],
    'discord' => ['Discord', 13],
    'apple' => ['Apple', 13],
    'x' => ['X', 13],
    'facebook' => ['Facebook', 13],
    'microsoft' => ['Microsoft', 11],
    'gitlab' => ['GitLab', 13],
    'linkedin' => ['LinkedIn', 11],
    'spotify' => ['Spotify', 13],
    'twitch' => ['Twitch', 13],
    'slack' => ['Slack', 13],
    'bitbucket' => ['Bitbucket', 13],
];

function fetch(string $url): string
{
    $body = @file_get_contents($url);
    if ($body === false) {
        fwrite(STDERR, "Download failed: {$url}\n");
        exit(1);
    }

    return $body;
}

$data = [];
$out = [];

foreach (ICONS as $slug => [$title, $major]) {
    $data[$major] ??= json_decode(fetch("https://cdn.jsdelivr.net/npm/simple-icons@{$major}/_data/simple-icons.json"), true)['icons'];

    $hex = null;
    foreach ($data[$major] as $icon) {
        if ($icon['title'] === $title) {
            $hex = strtoupper($icon['hex']);
            break;
        }
    }

    $svg = fetch("https://cdn.jsdelivr.net/npm/simple-icons@{$major}/icons/{$slug}.svg");
    if ($hex === null || preg_match('/<path d="([^"]+)"/', $svg, $match) !== 1 || preg_match('/^[MmZzLlHhVvCcSsQqTtAa0-9eE\s,.+-]+$/', $match[1]) !== 1) {
        fwrite(STDERR, "Unexpected data for {$slug}\n");
        exit(1);
    }

    $out[$slug] = ['title' => $title, 'hex' => $hex, 'path' => $match[1]];
}

$php = "<?php\n\ndeclare(strict_types=1);\n\n"
    . "// Generated by scripts/update-icons.php — do not edit by hand.\n"
    . "// Icon data from SimpleIcons (https://simpleicons.org), licensed CC0-1.0.\n"
    . "// Brand logos remain trademarks of their respective owners.\n\n"
    . 'return ' . var_export($out, true) . ";\n";

file_put_contents(__DIR__ . '/../src/UI/simple-icons.php', $php);
echo 'Wrote ' . count($out) . " icons.\n";
